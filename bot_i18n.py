LANGS = {"ru": RU}


def t(key: str, lang: str = DEFAULT_LANG, **kwargs) -> str:
    """Вернуть текст по ключу. Неизвестный ключ виден сразу, а не молчаливо."""
    table = LANGS.get(lang) or RU
    template = table.get(key)
    if template is None:
        return f"[{key}]"
    if kwargs:
        try:
            return template.format(**kwargs)
        except (KeyError, IndexError):
            # Недостающий параметр не должен ронять ответ пользователю.
            return template
    return template
